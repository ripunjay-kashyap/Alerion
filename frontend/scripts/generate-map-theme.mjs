// Generates src/lib/mapTheme.ts: the Mapbox Standard custom-theme LUT for the 2D map.
//
// Faithful port of mapgl's palette_to_lut(colors, method = "replace", intensity = 1)
// (walkerke/mapgl R/themes.R, lut_size = 32), including png::writePNG's
// double → byte conversion: (unsigned char)(v * 255 + 0.5).
// Run: node scripts/generate-map-theme.mjs
import { writeFileSync } from "node:fs";
import { deflateSync, crc32 } from "node:zlib";

// cyberpunk_2125 from https://gist.github.com/walkerke/e46f27b6f4c5c16fee6b4694ac11ef9d
export const PALETTE = [
  "#000000",
  "#0a0e27",
  "#1a1a2e",
  "#16213e",
  "#0f3460",
  "#533483",
  "#e94560",
  "#ff006e",
  "#8338ec",
  "#3a86ff",
  "#06ffa5",
  "#00f5ff",
];
const LUT_SIZE = 32;
const INTENSITY = 1;

// col2rgb(colors) / 255 → columns of [r, g, b]
const rgb = PALETTE.map((hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255));
const clamp = (v) => Math.max(0, Math.min(1, v));

// apply_palette_transform(..., method = "replace")
function replace(r, g, b) {
  const n = rgb.length;
  const gray = 0.299 * r + 0.587 * g + 0.114 * b;
  const pos = gray * (n - 1) + 1; // 1-based, as in R
  let low = Math.floor(pos);
  let high = Math.ceil(pos);
  const frac = pos - low;
  low = Math.max(1, Math.min(low, n));
  high = Math.max(1, Math.min(high, n));
  const [lo, hi] = [rgb[low - 1], rgb[high - 1]];
  return [0, 1, 2].map((c) => {
    const interp = lo[c] * (1 - frac) + hi[c] * frac;
    const orig = [r, g, b][c];
    return clamp(orig * (1 - INTENSITY) + interp * INTENSITY);
  });
}

// Image: height = LUT_SIZE (green), width = LUT_SIZE² (blue tile × red within tile)
export function lutPixels() {
  const width = LUT_SIZE * LUT_SIZE;
  const px = new Uint8Array(LUT_SIZE * width * 3);
  for (let tile = 0; tile < LUT_SIZE; tile++)
    for (let y = 0; y < LUT_SIZE; y++)
      for (let x = 0; x < LUT_SIZE; x++) {
        const out = replace(x / (LUT_SIZE - 1), y / (LUT_SIZE - 1), tile / (LUT_SIZE - 1));
        const i = (y * width + tile * LUT_SIZE + x) * 3;
        for (let c = 0; c < 3; c++) px[i + c] = Math.trunc(out[c] * 255 + 0.5);
      }
  return { px, width, height: LUT_SIZE };
}

function png({ px, width, height }) {
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr.set([8, 2, 0, 0, 0], 8); // 8-bit RGB, no alpha (as writePNG for a 3-plane array)
  const raw = Buffer.alloc(height * (width * 3 + 1));
  for (let y = 0; y < height; y++)
    raw.set(px.subarray(y * width * 3, (y + 1) * width * 3), y * (width * 3 + 1) + 1);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const uri = "data:image/png;base64," + png(lutPixels()).toString("base64");
  writeFileSync(
    new URL("../src/lib/mapTheme.ts", import.meta.url),
    `// Generated by scripts/generate-map-theme.mjs — do not edit by hand.
// Cyberpunk 2125 basemap theme: mapgl palette_to_lut(palette, method = "replace", intensity = 1).
export const MAP_THEME_PALETTE = ${JSON.stringify(PALETTE)};
export const MAP_THEME_LUT =
  "${uri}";
`,
  );
  console.log(`wrote src/lib/mapTheme.ts (${uri.length} chars)`);
}
